"""Stage 8: turn reports/results/*.json into reports/RESULTS.md (doc templates R1-R5 filled in).

    python -m soh.report
"""
import json

import pandas as pd

from soh import config

RES = config.REPORTS_DIR / "results"


def _load(name):
    p = RES / name
    return json.loads(p.read_text()) if p.exists() else None


def ms(d, digits=2):
    """'mean +/- std' from {'mean':..,'std':..}."""
    if d is None:
        return "-"
    if d["std"] and d["std"] > 0:
        return f"{d['mean']:.{digits}f} ± {d['std']:.{digits}f}"
    return f"{d['mean']:.{digits}f}"


def md_table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def build():
    data, tab, dp = _load("data_summary.json"), _load("tabular.json"), _load("deep.json")
    abl, nasa, exp = _load("ablation.json"), _load("nasa.json"), _load("explain_deploy.json")
    rep = _load("reproducibility.json")
    L = ["# Results: SOH estimation on MIT-Stanford-TRI and NASA PCoE",
         "",
         "_Auto-generated by `python -m soh.report` from `reports/results/`. All errors are in "
         "**% SOH** (SOH = QD / 1.1 Ah x 100). Mean ± std over seeds "
         f"{rep['seeds'] if rep else ''}; cell-wise official split (41 train / 43 primary / 40 secondary cells)._",
         ""]

    # ---------------------------------------------------------------- data
    c = data["cleaning"]
    L += ["## 1. Data and cleaning (O1)", "",
          md_table(["Step", "Rows / count"], [
              ["Raw per-cycle rows (124 cells after official cleaning, 140 raw)", f"{c['rows_raw']:,}"],
              ["Dropped: cycle 1", c["drop_cycle1"]],
              ["Dropped: impossible QD (<=0 or >1.2 Ah)", c["drop_impossible_QD"]],
              ["Flagged QD spikes (removed from TRAINING only)", c["flag_qd_outlier"]],
              ["Flagged IR glitches (set NaN, carried forward)", c["flag_ir_bad"]],
              ["Flagged temperature excursions (set NaN, carried forward)", c["flag_temp_bad"]],
              ["Clean rows", f"{c['rows_clean']:,}"],
              ["Cells per split", ", ".join(f"{k}: {v}" for k, v in c["cells_per_split"].items())],
              ["Rows per split", ", ".join(f"{k}: {v:,}" for k, v in c["rows_per_split"].items())],
          ]), "", "![capacity fade](figures/01_capacity_fade.png)", ""]

    # ---------------------------------------------------------------- audit
    audit = pd.read_csv(RES / "leakage_audit.csv")
    audit = audit[~audit["feature"].str.endswith("_rm5")]
    L += ["## 2. Leakage audit (O2)", "",
          "Each feature alone, on training cells only. `r2_single_cv` = cross-cell R² of a 1-feature "
          "tree (GroupKFold by cell). Threshold calibrated on known disguised labels: "
          f"**R² ≥ {c['leak_threshold']:.3f} ⇒ label-equivalent**. Rolling-mean (`_rm5`) copies "
          "inherit their parent's status and are omitted here.", "",
          md_table(["Feature", "Family", "Spearman (pooled)", "Spearman (within cell)", "Single-feature R²",
                    "Status", "Meaning"],
                   [[r.feature, r.family, f"{r.spearman_pooled:.2f}", f"{r.spearman_within:.2f}",
                     f"{r.r2_single_cv:.3f}", r.status, r.meaning] for r in audit.itertuples()]),
          "", "![feature scatter](figures/02_feature_scatter.png)", ""]

    # ---------------------------------------------------------------- R1
    rows = []
    allres = dict(tab["results"])
    if dp:
        allres.update(dp["results"])
    for key, r in allres.items():
        p, s = r["test_primary"], r["test_secondary"]
        model, fset = key.split(" | ")
        rows.append([model, fset, ms(p["RMSE"]), ms(p["MAE"]), ms(p["MAPE"]), ms(p["R2"], 3),
                     ms(s["RMSE"]), ms(s["MAE"]), ms(p["RMSE_80-85"]), ms(s["RMSE_80-85"]),
                     ms(p["EOL_abs_err_mean"], 0), f"{p['EOL_undefined_cells']['mean']:.0f} / 43",
                     f"{s['EOL_undefined_cells']['mean']:.0f} / 40",
                     ms(p["cell_RMSE_worst"]), ms(s["cell_RMSE_worst"])])
    L += ["## 3. Main results — template R1 (O3)", "",
          md_table(["Model", "Features", "Primary RMSE", "Primary MAE", "Primary MAPE %", "Primary R²",
                    "Secondary RMSE", "Secondary MAE", "EOL-band (80–85 %) RMSE prim.",
                    "EOL-band RMSE sec.", "Mean \\|EOL error\\| prim. (cycles, alarmed cells)",
                    "Missed EOL alarms prim.", "Missed EOL alarms sec.", "Worst-cell RMSE prim.", "Worst-cell RMSE sec."], rows),
          "", f"EOL error uses an alarm at {config.EOL_ALARM_SOH} % SOH (batch-3 cells stop at "
          "80.0–80.15 %, so a strict 80 % crossing never occurs there). It is computed on raw, "
          "unsmoothed per-cycle estimates, so a single noisy low estimate triggers an early alarm. "
          "A **missed alarm** = the cell truly crossed the alarm level but the estimate never did "
          "(the model is optimistic near end of life) — the dangerous failure mode for a BMS.", "",
          f"Figures below use the model with the lowest mean of primary and secondary RMSE: "
          f"**{(_load('best_model.json') or {}).get('best_model', '')}**.", "",
          "![pred vs true](figures/03_pred_vs_true.png)", "",
          "![trajectories primary](figures/04_trajectories_test_primary.png)", "",
          "![trajectories secondary](figures/04_trajectories_test_secondary.png)", "",
          "![error by band](figures/05_error_by_band.png)", ""]
    tun = tab["tuning"]
    L += ["**Tuned hyper-parameters** (RandomizedSearchCV, GroupKFold(5) on training cells):", "",
          md_table(["Model", "Inner-CV RMSE", "Best parameters"],
                   [[k, f"{v['cv_rmse']:.3f}", "`" + json.dumps(v["params"], default=str) + "`"]
                    for k, v in tun.items() if v]), ""]
    if dp:
        L += ["**Deep-model window length** (LSTM, seed 0):", "",
              md_table(["k (cycles)", "Primary RMSE", "Secondary RMSE"],
                       [[k, ms(v["test_primary"]["RMSE"]), ms(v["test_secondary"]["RMSE"])]
                        for k, v in dp["window_ablation"].items()]), ""]

    # ---------------------------------------------------------------- R2 / R3
    a = abl["ablation"]
    base = a["A4_plus_history"]["test_primary"]["RMSE"]["mean"]
    rows = []
    for k, v in a.items():
        if "test_primary" in v:
            rows.append([k, ms(v["test_primary"]["RMSE"]), ms(v["test_secondary"]["RMSE"]),
                         f"{v['test_primary']['RMSE']['mean'] - base:+.2f}"])
        else:
            rows.append([k, "(pooled random-row test) " + ms(v["test_pool"]["RMSE"]), "-",
                         f"{v['test_pool']['RMSE']['mean'] - base:+.2f}"])
    L += ["## 4. Ablation ladder — template R2 (XGBoost, tuned once on A4)", "",
          md_table(["Step", "Primary RMSE", "Secondary RMSE", "Δ primary vs A4"], rows), "",
          "![ablation](figures/07_ablation.png)", ""]
    lk = abl["leakage"]
    L += ["## 5. Leakage demonstration — template R3 (O4)", "",
          "Same 84 cells (train + primary), same model, 50 % held out either as random **rows** or as "
          "whole **cells**.", "",
          md_table(["Model", "Random-row split RMSE", "Cell-wise split RMSE", "Inflation factor"],
                   [[m, f"{v['random_row_rmse']:.3f} ± {v['random_row_std']:.3f}",
                     f"{v['cell_wise_rmse']:.3f} ± {v['cell_wise_std']:.3f}", f"{v['inflation']:.1f}x"]
                    for m, v in lk.items()]), "", "![leakage](figures/07b_leakage.png)", "",
          f"**Robustness:** XGBoost (A4) over 10 random 80/20 *cell* splits of all 124 cells: "
          f"RMSE {abl['robustness']['mean']:.3f} ± {abl['robustness']['std']:.3f} % SOH "
          f"(range {min(abl['robustness']['rmse_each']):.2f}–{max(abl['robustness']['rmse_each']):.2f}).", ""]

    # ---------------------------------------------------------------- R4
    rows = []
    for m, per in nasa["lobo"].items():
        v = [per[c] for c in config.NASA_CELLS]
        rows.append([m, "NASA LOBO (label soh)", *[f"{x:.2f}" for x in v],
                     f"{pd.Series(v).mean():.2f} ± {pd.Series(v).std(ddof=0):.2f}"])
    for m, per in nasa["zero_shot"].items():
        v = [per[c] for c in config.NASA_CELLS]
        rows.append([m, f"MIT → NASA zero-shot (soh_init); MIT sanity {per['MIT_primary_sanity']:.2f}",
                     *[f"{x:.2f}" for x in v], f"{pd.Series(v).mean():.2f} ± {pd.Series(v).std(ddof=0):.2f}"])
    lr = nasa["nasa_label_range"]
    L += ["## 6. NASA — template R4 (O5)", "",
          md_table(["Model", "Setting", *config.NASA_CELLS, "Mean ± std"], rows), "",
          f"NASA labels go down to {lr['soh_min']:.1f} % SOH ({lr['soh_init_min']:.1f} % soh_init); MIT training "
          f"labels only reach {lr['mit_train_soh_init_min']:.1f} % soh_init, and trees cannot extrapolate below "
          "their lowest training label.", "",
          "![nasa lobo](figures/08_nasa_lobo.png)", "", "![nasa zero shot](figures/09_nasa_zero_shot.png)", ""]

    # ---------------------------------------------------------------- explain
    pm, pb = pd.read_csv(RES / "permutation_importance_main.csv"), pd.read_csv(RES / "permutation_importance_bms.csv")
    shp = pd.read_csv(RES / "shap_mean_abs.csv", index_col=0).iloc[:, 0]
    L += ["## 7. Explainability (O6)", "",
          "Grouped permutation importance on 4,000 primary-test cycles (a feature is permuted together "
          "with its `d_`, `r_` and `_rm5` copies so correlated copies do not split the credit).", "",
          md_table(["Rank", "Main model (A4) group", "RMSE increase", "BMS model (A2) group", "RMSE increase"],
                   [[i + 1, pm.iloc[i]["group"], f"{pm.iloc[i]['rmse_increase']:.3f}",
                     pb.iloc[i]["group"] if i < len(pb) else "", f"{pb.iloc[i]['rmse_increase']:.3f}" if i < len(pb) else ""]
                    for i in range(min(10, len(pm)))]), "",
          "Top mean |SHAP| (main model): " + ", ".join(f"`{k}` {v:.2f}" for k, v in shp.iloc[:8].items()), "",
          "![shap](figures/06_shap_beeswarm.png)", "", "![waterfall](figures/06_shap_waterfall.png)", ""]

    # ---------------------------------------------------------------- R5
    fp = dict(exp["footprint"])
    if dp:
        fp.update(dp["footprint"])
    L += ["## 8. Deployment footprint — template R5 (O7)", "",
          md_table(["Model", "Parameters / trees", "File size (KB)", "CPU inference per cycle (ms)",
                    "Needs full discharge?"],
                   [[k, v["params"], f"{v['size_kb']:.0f}", f"{v['ms_per_cycle']:.2f}", v["needs_full_discharge"]]
                    for k, v in fp.items()]), "",
          "Timing is single-cycle Python inference on one CPU core of the build machine (includes Python "
          "call overhead), not a microcontroller.", "",
          "![health monitor](figures/10_health_monitor_demo.png)", ""]

    if rep:
        L += ["## 9. Reproducibility", "", md_table(["Item", "Value"], [[k, v] for k, v in rep.items()]), ""]
    out = config.REPORTS_DIR / "RESULTS.md"
    out.write_text("\n".join(L))
    print("wrote", out)


if __name__ == "__main__":
    build()
